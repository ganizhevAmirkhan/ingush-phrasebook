function main() {
  const wb = JSON.parse(fs.readFileSync(WB, "utf8"));
  const have = new Set(wb.units.map((u) => (u.ing || "").replace(/\s+/g, " ").trim().slice(0, 35)));
  let n = wb.units.length;
  let added = 0;
  for (const row of NEXT) {
    const key = row.ing.replace(/\s+/g, " ").trim().slice(0, 35);
    if ([...have].some((h) => h.includes(key.slice(0, 20)) || key.includes(h.slice(0, 20)))) continue;
    n += 1;
    wb.units.push({
      id: `beki_${String(n).padStart(3, "0")}`,
      status: "draft",
      ing: row.ing,
      ru: row.ru,
      phrases: [],
      words: [],
      notes: "продолжение: черновик RU — поправь смысл",
    });
    have.add(key);
    added += 1;
  }
  wb.updatedAt = new Date().toISOString();
  wb.note = "ING→RU. Продолжение: Саад → Хасан/поле. Draft на правку.";
  wb.direction = "ing→ru";
  const json = JSON.stringify(wb, null, 2) + "\n";
  fs.writeFileSync(WB, json, "utf8");
  fs.writeFileSync(SEED, json, "utf8");
  process.stdout.write(`added=${added} total=${wb.units.length}\n`);
}

main();
