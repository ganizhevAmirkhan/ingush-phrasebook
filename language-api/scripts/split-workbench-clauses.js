/**
 * Split workbench units by clause punctuation (, . ! ? : ; —)
 * Direction: ING first. RU is split too when counts match; else RU stays on first clause as draft.
 */
const fs = require("node:fs");
const path = require("node:path");

const FILE = path.join(__dirname, "..", "data", "workbench", "synovya-beki.workbench.json");
const SEED = path.join(__dirname, "..", "public", "tools", "seed", "synovya-beki.workbench.json");

function splitClauses(text) {
  const s = String(text || "").replace(/\s+/g, " ").trim();
  if (!s) return [];
  const parts = [];
  let buf = "";
  for (let i = 0; i < s.length; i++) {
    const ch = s[i];
    buf += ch;
    if (",.!?;:".includes(ch) || ch === "—" || ch === "–") {
      const next = s[i + 1] || "";
      // keep abbreviations-ish digits like 1. alone? keep going if letter after period without space rare
      if (ch === "." && /\d/.test(s[i - 1] || "")) continue;
      const piece = buf.trim();
      if (piece.length > 1) parts.push(piece);
      buf = "";
      while (s[i + 1] === " ") i++;
    }
  }
  const tail = buf.trim();
  if (tail) parts.push(tail);
  return parts.filter((p) => p.replace(/[,.!?;:—–]/g, "").trim().length > 0);
}

