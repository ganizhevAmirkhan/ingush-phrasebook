function norm(s) {
  return String(s || "")
    .toLowerCase()
    .replace(/[Ӏӏ]/g, "1")
    .replace(/[,.!?;:—–"«»]/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

function findRu(ingClause) {
  const n = norm(ingClause);
  for (const [ing, ru] of RU_BY_ING) {
    const ni = norm(ing);
    if (n === ni || n.startsWith(ni) || ni.startsWith(n)) return ru;
  }
  return "";
}

function main() {
  const wb = JSON.parse(fs.readFileSync(FILE, "utf8"));
  const out = [];
  let n = 0;
  for (const u of wb.units) {
    const ingParts = splitClauses(u.ing);
    const ruParts = splitClauses(u.ru);
    if (ingParts.length <= 1) {
      n += 1;
      out.push({
        ...u,
        id: `beki_${String(n).padStart(3, "0")}`,
        phrases: [],
        words: [],
        notes: u.notes || "",
      });
      continue;
    }
    for (let i = 0; i < ingParts.length; i++) {
      n += 1;
      let ru = findRu(ingParts[i]);
      if (!ru && ruParts.length === ingParts.length) ru = ruParts[i];
      if (!ru && i === 0 && ruParts.length) ru = u.ru;
      out.push({
        id: `beki_${String(n).padStart(3, "0")}`,
        status: ru ? "draft" : "draft",
        ing: ingParts[i],
        ru: ru || "",
        phrases: [],
        words: [],
        notes: ru ? "clause-split; проверь RU" : "clause-split; нужен RU",
        parentId: u.id,
      });
    }
  }

  wb.units = out;
  wb.note = "ING→RU, дроблено по запятым и точкам. Проверь смысловой RU.";
  wb.updatedAt = new Date().toISOString();
  wb.direction = "ing→ru";
  const json = JSON.stringify(wb, null, 2) + "\n";
  fs.writeFileSync(FILE, json, "utf8");
  fs.writeFileSync(SEED, json, "utf8");
  process.stdout.write(`units: ${out.length}\n`);
  out.slice(0, 12).forEach((u) => {
    process.stdout.write(`[${u.id}] ${u.ing.slice(0, 50)}… → ${u.ru.slice(0, 50) || "—"}\n`);
  });
}

main();
